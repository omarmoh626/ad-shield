// Regenerates the command and module support list in docs/SUPPORT.md from the cmdlet registry.
// Usage: node scripts/support-list.mjs          (writes the file)
//        node scripts/support-list.mjs --check  (exits 1 when the file is out of date)
// The registry is TypeScript, so it is loaded through Vite's SSR loader (a dev dependency). Nothing runs in a browser.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = fileURLToPath(new URL('..', import.meta.url))
const target = new URL('../docs/SUPPORT.md', import.meta.url)
const START = '<!-- support-list:start (generated by scripts/support-list.mjs; do not edit by hand) -->'
const END = '<!-- support-list:end -->'

const server = await createServer({ root, logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom' })
let registry
let parametersOf
try {
  const runtime = await server.ssrLoadModule('/src/ps/runtime.ts')
  const reg = await server.ssrLoadModule('/src/ps/registry.ts')
  registry = runtime.createDefaultRegistry()
  parametersOf = reg.parametersOf
} finally {
  await server.close()
}

const code = (text) => `\`${text}\``
const cell = (text) => text.replace(/\|/g, '\\|')
const TYPE = { string: 'string', 'string[]': 'string[]', int: 'int', bool: 'bool', object: 'object', 'object[]': 'object[]', scriptblock: 'scriptblock', hashtable: 'hashtable', secure: 'securestring' }

function parameterText(parameter) {
  const name = parameter.position !== undefined ? `[-${parameter.name}]` : `-${parameter.name}`
  const type = parameter.type === 'switch' ? '' : ` <${TYPE[parameter.type] ?? parameter.type}>`
  const notes = [parameter.mandatory ? 'required' : '', parameter.pipeline ? 'pipeline' : '', parameter.values?.length ? parameter.values.join('\\|') : ''].filter(Boolean)
  return `${code(name + type)}${notes.length ? ` (${notes.join(', ')})` : ''}`
}

const specs = registry.list()
const modules = [...new Set(specs.map((spec) => spec.module))].sort()
const lines = [START, '', `${specs.length} cmdlets in ${modules.length} modules.`, '', '| Module | Cmdlets | Aliases |', '| --- | --- | --- |']
for (const module of modules) {
  const inModule = specs.filter((spec) => spec.module === module)
  const aliases = inModule.flatMap((spec) => spec.aliases ?? [])
  lines.push(`| ${code(module)} | ${inModule.map((spec) => code(spec.name)).join(', ')} | ${aliases.map(code).join(', ')} |`)
}
lines.push('', 'Supported parameters. `-WhatIf` and `-Confirm` appear for every cmdlet that supports them.', '', '| Cmdlet | Parameters | `-WhatIf` |', '| --- | --- | --- |')
for (const spec of specs) {
  const parameters = parametersOf(spec)
  lines.push(`| ${code(spec.name)} | ${parameters.length ? cell(parameters.map(parameterText).join(', ')) : 'none'} | ${spec.supportsWhatIf ? 'yes' : 'no'} |`)
}
lines.push('', END)
const block = lines.join('\n')

const current = readFileSync(target, 'utf8')
const from = current.indexOf(START)
const to = current.indexOf(END)
if (from < 0 || to < 0) throw new Error('docs/SUPPORT.md has no support-list markers.')
const next = current.slice(0, from) + block + current.slice(to + END.length)
if (process.argv.includes('--check')) {
  if (next !== current) { console.error('docs/SUPPORT.md is out of date. Run: node scripts/support-list.mjs'); process.exit(1) }
  console.log(`docs/SUPPORT.md is up to date (${specs.length} cmdlets).`)
} else {
  writeFileSync(target, next)
  console.log(`Wrote ${specs.length} cmdlets in ${modules.length} modules to docs/SUPPORT.md.`)
}
